"""Phase I — Forge verification.

These never invoke `forge` — the toolchain may not be installed, and the interesting
behaviour is what happens *around* the subprocess: what translates into a mechanical check,
what deliberately does not, and what the status is when nothing ran.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from engine.core.models.protocol import InvariantStatus
from engine.protocol.verify import forge
from tests.protocol.conftest import build_from_sources
from tests.protocol.conftest_sources import VAULT_PROJECT


@pytest.fixture
def built(tmp_path):
    from engine.protocol.understand import understand

    code, graph, repo = build_from_sources(tmp_path, VAULT_PROJECT, name="verify")
    return understand(code, graph, repo), Path(repo.root), tmp_path


# ── Phase I ───────────────────────────────────────────────────────────────────


def test_without_forge_everything_stays_a_candidate(built, monkeypatch):
    """A missing toolchain is a note, not a failure — and must never leave an invariant
    looking checked when nothing ran."""
    model, repo_root, run_dir = built
    monkeypatch.setattr(forge, "available", lambda: False)

    result, run = forge.verify(model, repo_root, run_dir)

    assert not run.available
    assert run.passed == run.failed == 0
    assert all(i.status is InvariantStatus.CANDIDATE for i in result.invariants)
    assert any("not on PATH" in note for note in run.notes or [])


def test_only_mechanically_checkable_invariants_are_translated(built):
    """A generated test that approximates an invariant produces a confident FAIL on correct
    code, which looks like evidence and is not."""
    model, _, _ = built

    translated = [i for i in model.invariants if forge._translatable(model, i) is not None]
    skipped = [i for i in model.invariants if forge._translatable(model, i) is None]

    assert translated, "a vault with a supply and balances should yield at least one"
    assert skipped, "solvency invariants are not mechanically checkable and must be skipped"
    assert all(i.kind.value in ("supply", "monotonicity") for i in translated)


def test_a_generated_test_is_deterministic_and_names_its_invariant(built):
    model, _, _ = built
    invariant = next(
        i for i in model.invariants if forge._translatable(model, i) is not None
    )

    first = forge._translatable(model, invariant)
    second = forge._translatable(model, invariant)

    assert first == second
    assert invariant.statement in first
    assert "Generated by AuditOS" in first
    assert forge._test_name(invariant) in first


def test_the_supply_check_is_sound_rather_than_complete(built):
    """Solidity cannot enumerate a mapping, so the sum is over touched actors only. That
    makes a violation real and a pass inconclusive — stated in the test, not hidden."""
    model, _, _ = built
    supply = next(
        forge._translatable(model, i) for i in model.invariants if i.kind.value == "supply"
    )
    assert "assertLe" in supply
    assert "under-count" in supply


def test_forge_json_parsing_is_tolerant_of_shape_changes():
    """A parse failure must leave invariants CANDIDATE, never silently mark them verified."""
    assert forge._parse("not json at all") == {}
    assert forge._parse('{"a/B.t.sol:X": {"test_results": {"t": {"status": "Success"}}}}') == {
        "X": True
    }
    assert forge._parse('{"a/B.t.sol:X": {"test_results": {"t": {"status": "Failure"}}}}') == {
        "X": False
    }
